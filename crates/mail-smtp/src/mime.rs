//! MIME assembly and envelope derivation from an [`OutgoingMessage`].
//!
//! The body is built with [`mail-builder`](mail_builder). Blind-carbon-copy
//! recipients are deliberately **never** written as a header — they appear only
//! in the SMTP envelope (`RCPT TO`), which [`collect_recipients`] returns
//! alongside the `To`/`Cc` addresses.

use std::sync::atomic::{AtomicU64, Ordering};
use std::time::{SystemTime, UNIX_EPOCH};

use axomail_core::{Address, MailError, OutgoingMessage};
use mail_builder::MessageBuilder;
use mail_builder::headers::address::Address as BuilderAddress;
use mail_builder::headers::content_type::ContentType;

/// EHLO/HELO identity. An address literal keeps the local host name out of the
/// wire while staying RFC 5321 valid.
pub(crate) const HELO_HOST: &str = "[127.0.0.1]";

/// A rendered outgoing message together with the `Message-ID` it was assigned.
///
/// The identical `bytes` are handed to SMTP submission **and** to the IMAP
/// `APPEND` that files the Sent copy, so the delivered message and the filed
/// copy are byte-for-byte the same and share the returned `message_id`. The id
/// is bracket-free (no `<>`), matching how the storage layer records
/// `Message-ID`.
#[derive(Debug, Clone)]
pub struct RenderedMessage {
    /// The complete RFC 5322 byte stream.
    pub bytes: Vec<u8>,
    /// The generated `Message-ID`, without angle brackets.
    pub message_id: String,
}

/// Renders `message` into an RFC 5322 byte stream, returning it alongside the
/// generated `Message-ID`.
///
/// `text_body` is always present. `html_body`, when set, is emitted as the
/// second part of a `multipart/alternative`; attachments wrap the result in a
/// `multipart/mixed`. `Date` is generated by the builder and `Message-ID` is
/// generated here from the sender's domain. No `Bcc` header is written.
///
/// # Errors
///
/// Returns [`MailError::Protocol`] if serialization fails (an internal writer
/// error; not expected for in-memory buffers).
pub fn render_message(message: &OutgoingMessage) -> Result<RenderedMessage, MailError> {
    let message_id = generate_message_id(message.from.email.domain());
    let mut builder = MessageBuilder::new()
        .from(builder_address(&message.from))
        .to(address_list(&message.to))
        .subject(message.subject.as_str())
        .message_id(message_id.clone())
        .text_body(message.text_body.as_str());

    if !message.cc.is_empty() {
        builder = builder.cc(address_list(&message.cc));
    }
    if let Some(reply_to) = &message.reply_to {
        builder = builder.reply_to(builder_address(reply_to));
    }
    if let Some(html) = &message.html_body {
        builder = builder.html_body(html.as_str());
    }
    for attachment in &message.attachments {
        builder = builder.attachment(
            ContentType::new(attachment.mime_type.as_str()),
            attachment.filename.as_str(),
            attachment.bytes.as_slice(),
        );
    }

    let bytes = builder.write_to_vec().map_err(|err| MailError::Protocol {
        message: format!("failed to serialize outgoing message: {err}"),
    })?;
    Ok(RenderedMessage { bytes, message_id })
}

/// Collects the SMTP envelope recipients: `To`, then `Cc`, then `Bcc`.
///
/// Duplicates (by exact address) are dropped so a recipient listed twice is not
/// handed two copies. Order is preserved for deterministic tests.
#[must_use]
pub(crate) fn collect_recipients(message: &OutgoingMessage) -> Vec<String> {
    let mut recipients: Vec<String> = Vec::new();
    for address in message.to.iter().chain(&message.cc).chain(&message.bcc) {
        let email = address.email.as_str();
        if !recipients.iter().any(|existing| existing == email) {
            recipients.push(email.to_owned());
        }
    }
    recipients
}

/// Converts a core [`Address`] into a mail-builder address, preserving any
/// display name.
fn builder_address(address: &Address) -> BuilderAddress<'_> {
    BuilderAddress::new_address(address.display_name.as_deref(), address.email.as_str())
}

/// Builds a mail-builder address list from a slice of core addresses.
fn address_list(addresses: &[Address]) -> BuilderAddress<'_> {
    BuilderAddress::new_list(addresses.iter().map(builder_address).collect())
}

/// Generates a unique, bracket-free `Message-ID` local/domain value.
///
/// Uniqueness comes from the wall-clock timestamp, a process-wide counter, and
/// a randomly seeded hash, so two messages built in the same nanosecond still
/// differ. The sender's domain is used as the right-hand side.
fn generate_message_id(domain: &str) -> String {
    use std::hash::{BuildHasher, Hasher, RandomState};

    static COUNTER: AtomicU64 = AtomicU64::new(0);

    let nanos = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|elapsed| elapsed.as_nanos())
        .unwrap_or(0);
    let sequence = COUNTER.fetch_add(1, Ordering::Relaxed);

    let mut hasher = RandomState::new().build_hasher();
    hasher.write_u128(nanos);
    hasher.write_u64(sequence);
    let entropy = hasher.finish();

    let domain = if domain.is_empty() {
        "localhost"
    } else {
        domain
    };
    format!("{nanos:x}.{entropy:x}@{domain}")
}
